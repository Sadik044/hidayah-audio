-- ==============================================================================
-- 1. SEC-SB-03: PARENT SERIES PUBLICATION ENFORCEMENT ON EPISODES RLS
-- ==============================================================================

-- Index to optimize episodes lookup by series and publication status
-- Note: idx_series_id_published was evaluated and omitted because public.series.id
-- is already uniquely indexed by primary key series_pkey.
CREATE INDEX IF NOT EXISTS idx_episodes_series_published
  ON public.episodes (series_id, published);

-- Drop all existing public SELECT policies on episodes to prevent permissive OR policy duplication
-- Specifically drops the active production policy "Public read published episodes"
DROP POLICY IF EXISTS "Public read published episodes" ON public.episodes;
DROP POLICY IF EXISTS "Public can view published episodes" ON public.episodes;
DROP POLICY IF EXISTS "Public read episodes" ON public.episodes;
DROP POLICY IF EXISTS "Allow public read access to published episodes" ON public.episodes;

-- Hardened Public SELECT Policy:
-- Both the episode AND its parent series MUST have published = true.
-- If parent series is unpublished (draft), all associated episodes are hidden
-- from unauthenticated and non-admin callers, even if individual episodes have published = true.
-- Note: Admin AAL2 users continue to read all episodes via "Admins read all episodes" policy.
CREATE POLICY "Public can view published episodes"
  ON public.episodes
  FOR SELECT
  TO anon, authenticated
  USING (
    published = true
    AND EXISTS (
      SELECT 1 FROM public.series s
      WHERE s.id = episodes.series_id
        AND s.published = true
    )
  );

